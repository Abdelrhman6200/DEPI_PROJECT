export function translate(locale: Locale, key: TKey, vars?: Record<string, string | number>): string {
  const entry = D[key];
  let s: string = entry ? entry[locale === 'ar' ? 1 : 0] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function hasKey(key: string): key is TKey {
  return Object.prototype.hasOwnProperty.call(D, key);
}

/** "R04_foot_infection" -> "Foot infection", "er_accepting" -> "Er accepting". */
export function humanize(value: string): string {
  const s = value
    .replace(/^R\d+_/, '')
    .replace(/[_-]+/g, ' ')
    .trim()
    .toLowerCase();
  return s.replace(/^\w/, (c) => c.toUpperCase());
}

/** Translate an enum-like value under a prefix (e.g. 'cl.' + care_level), falling back to a humanised value. */
export function translateEnum(locale: Locale, prefix: string, value: string | null | undefined): string {
  if (!value) return '';
  const key = `${prefix}${value}`;
  if (hasKey(key)) return translate(locale, key);
  return humanize(value);
}
